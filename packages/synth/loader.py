"""`synth load --target snowflake|duckdb`: create the schemas and load every table."""
from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path

from connectors.warehouse import DuckDBWarehouse, SnowflakeWarehouse, Warehouse
from domain.config import REPO_ROOT, settings
from synth import schema
from synth.warehouse_data import build_rows


def write_ddl_file() -> Path:
    path = REPO_ROOT / "infra" / "snowflake" / "ddl.sql"
    path.write_text("-- Generated by `synth ddl`. TIQ_POC synthetic source schemas (Data Spec section 2).\n"
                    + ";\n".join(schema.ddl("snowflake")) + ";\n", encoding="utf-8")
    return path


def load(target: str = "duckdb", reset_account: bool = False, log=print) -> dict:
    rows = build_rows()
    if target == "snowflake":
        wh: Warehouse = _prepare_snowflake(reset_account, log)
    else:
        path = settings.duckdb_path
        if os.path.exists(path):
            os.remove(path)
        wh = DuckDBWarehouse(path)
    for stmt in schema.ddl("snowflake" if target == "snowflake" else "duckdb"):
        wh.execute(stmt)
    counts = {}
    for table, data in rows.items():
        cols = schema.columns(table) + ["LOADED_AT", "SOURCE_BATCH_ID"]
        counts[table] = wh.insert_rows(table, cols, data)
        log(f"loaded {table}: {counts[table]} rows")
    return {"target": target, "tables": counts, "loaded_at": datetime.now(timezone.utc).isoformat()}


def _prepare_snowflake(reset_account: bool, log) -> SnowflakeWarehouse:
    """Create the database (optionally dropping every other user database first) and an XS warehouse."""
    sf = SnowflakeWarehouse()
    con = sf.connect(with_database=False)
    cur = con.cursor()
    try:
        if reset_account:
            cur.execute("show databases")
            names = [r[1] for r in cur.fetchall()]
            for name in names:
                if name.upper() in ("SNOWFLAKE", "SNOWFLAKE_SAMPLE_DATA") or name.upper().startswith("USER$"):
                    continue
                if name.upper() == sf.database.upper():
                    continue
                log(f"dropping database {name}")
                try:
                    cur.execute(f'drop database if exists "{name}"')
                except Exception as exc:  # the loader role may not own it
                    log(f"could not drop {name}: {str(exc)[:120]}")
        # Create only what is missing: a loader role may use objects it is not allowed to create
        # (infra/snowflake/admin_setup.sql creates them as ACCOUNTADMIN).
        cur.execute(f"show warehouses like '{settings.snowflake_warehouse}'")
        if not cur.fetchall():
            cur.execute(f"create warehouse {settings.snowflake_warehouse} warehouse_size = 'XSMALL' "
                        "auto_suspend = 60 auto_resume = true initially_suspended = true")
        cur.execute(f"show databases like '{sf.database}'")
        if not cur.fetchall():
            cur.execute(f"create database {sf.database}")
        cur.execute(f"use database {sf.database}")
    finally:
        cur.close()
    sf._con = con
    return sf
